const verbose = process.argv.includes('-v');
const strip = s => s.replace(/<[^>]+>/g, '');
let fail = 0;
// некорректный ввод
for (const bad of ['привет как дела у тебя сегодня', 'abc', 'В треугольнике ABC AB = 5 и BC = 7.']) {
  const r = await solveGeometryProblem(bad, {});
  const pass = !r.ok && /Некорректная задача|Слишком короткое/.test(r.error);
  if (!pass) fail++;
  console.log((pass ? 'ok   ' : 'FAIL ') + '[некорректный ввод] ' + bad + (pass ? '' : ' → ' + (r.error || 'решено')));
}
for (const [text, expected] of CASES) {
  const r = await solveGeometryProblem(text, {});
  const got = r.ok ? r.answers.map(a => a.value) : [];
  const ok = r.ok && got.length === expected.length && got.every((v, i) => Math.abs(v - expected[i]) < 1e-6 * Math.max(1, Math.abs(expected[i])));
  const methodOk = r.ok && r.method !== 'coords';
  let gmsOk = false;
  try { gmsOk = r.ok && compile(r.gms).success; } catch (e) { gmsOk = false; }
  const pass = ok && methodOk && gmsOk;
  if (!pass) fail++;
  console.log((pass ? 'ok   ' : 'FAIL ') + text.slice(0, 90) + (pass ? '' : '\n     ' + (r.ok ? 'ответ ' + got.join(', ') + ' (ожидалось ' + expected.join(', ') + '), метод ' + r.method + ', чертёж ' + (gmsOk ? 'ok' : 'ошибка') : r.error)));
  if (verbose && r.ok) r.steps.forEach((s, i) => console.log('       ' + (i + 1) + '. ' + strip(s.html)));
}
console.log(fail ? '\n' + fail + ' из ' + CASES.length + ' не прошли' : '\nВсе ' + CASES.length + ' задач решены верно');
process.exit(fail ? 1 : 0);
